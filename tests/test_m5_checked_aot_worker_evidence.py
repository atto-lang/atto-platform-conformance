"""M5 executed-run historical record structure, not live signed CI attestation."""
import copy
import hashlib
import json
from pathlib import Path
import re
import unittest

ROOT = Path(__file__).resolve().parents[1]
DOC = json.loads((ROOT/"evidence/m5/checked-actor-native-and-worker-20261107.json").read_text())
SCHEMA = json.loads((ROOT/"contracts/m5-ownership-supervisor-v1.json").read_text())
M4 = json.loads((ROOT/"contracts/m4-shared-actor-counter-v1.json").read_text())
SHA40 = re.compile("[0-9a-f]{40}\Z")
SHA64 = re.compile("[0-9a-f]{64}\Z")

def enforce(ok, why):
    if not ok: raise AssertionError(why)

def checked(record):
    enforce(record["schema"] == "atto.m5.canonical-aot-and-async-worker-evidence.v1",
            "record schema")
    enforce(SCHEMA["schema"] == "atto.m5.actor-ownership-supervision-contract.v1",
            "ownership contract")
    src = (ROOT/M4["fixture"]).read_bytes()
    enforce(record["source"]["git_blob_sha"] == M4["source_git_blob_sha"],
            "canonical source blob")
    enforce(record["source"]["sha256"] == hashlib.sha256(src).hexdigest(), "source digest")
    for key, repo in (("canonical_checked_ir_to_graalvm","atto-source.llvm"),
                      ("graalvm_async_worker_host","atto-source.java")):
        item=record[key]
        enforce(item["repo"] == "atto-lang/"+repo, "repository provenance")
        enforce(SHA40.fullmatch(item["head_sha"]) is not None, "exact head missing")
        enforce(item["run_url"].startswith("https://github.com/atto-lang/"+repo+
                                            "/actions/runs/"), "source CI URL")
        enforce(item["conclusion"] == "success", "unsuccessful job")
        enforce(SHA64.fullmatch(item["native_image_sha256"]) is not None,
                "compiled native artifact digest")
    a=record["canonical_checked_ir_to_graalvm"]
    enforce(a["original_source_git_blobs_verified"] == 57, "original C++ compiler proof")
    enforce(a["negative_source_admission_tests"] == 9, "canonical source admission")
    enforce(SHA40.fullmatch(a["java_codegen_git_blob"]) is not None, "backend Git blob")
    enforce(SHA64.fullmatch(a["exporter_binary_sha256"]) is not None, "exporter SHA")
    enforce(SHA64.fullmatch(a["generated_java_sha256"]) is not None, "generated source SHA")
    enforce(a["guest_executed"] is True, "no compiled guest")
    enforce((a["native_return"],a["guest_sends"],a["actor_closes"],
             a["actor_state_digest"],a["observed_guest_gc_collections"]) ==
            (43,3,2,7021,0), "canonical actor semantic mismatch")
    w=record["graalvm_async_worker_host"]
    enforce(w["host_worker_guest_executed"] is True, "native host not executed")
    enforce(w["checked_ir_shape_tests"] == 18, "IR negative suite missing")
    enforce(w["concurrent_accepted_messages"] == 100000 and
            w["neighbor_messages"] == 1000, "worker queue pressure missing")
    enforce(w["actor_state"] == 100000 and w["neighbor_state"] == 2050,
            "worker state mismatch")
    enforce(w["independent_worker_threads_observed"] is True and
            w["capacity_full_refusal_observed"] is True, "not independently scheduled/bounded")
    enforce(w["supervisor_control_notices"] == 1 and
            w["failed_turns_accounted"] == 1 and
            w["abandoned_queued_messages_accounted"] == 1,
            "supervisor failure/abandonment accounting")
    enforce(w["observed_runtime_gc_collections"] == 0, "not Epsilon no-collection")
    enforce(w["managed_heap_delta_bytes"] == 25690112, "heap measurement tampered")
    enforce(w["managed_heap_growth_budget_bytes"] == 8388608, "heap threshold altered")
    enforce(w["managed_heap_delta_bytes"] > w["managed_heap_growth_budget_bytes"],
            "memory result reversed")
    enforce(w["managed_heap_budget"] == "NOT_QUALIFIED",
            "unearned sustainable Epsilon claim")
    for key,val in record["unverified_release_gates"].items():
        enforce(val == ("NOT_QUALIFIED" if key == "graalvm_sustainable_managed_heap_under_epsilon"
                        else "NOT_EXECUTED"), "unearned release certification: "+key)
    notes=" ".join(record["notes"])
    enforce("not signed workflow attestation" in notes, "false evidence authority")
    enforce("not generated by canonical .atto codegen" in notes,
            "false actor scheduling parity")
    enforce("25,690,112" in notes, "heap growth hidden")
    return True

class M5HistoricalReceipt(unittest.TestCase):
    def test_record_is_structurally_consistent_not_signed(self):
        self.assertTrue(checked(DOC))

    def invalid(self, change):
        item=copy.deepcopy(DOC)
        change(item)
        with self.assertRaises((AssertionError, KeyError, TypeError)):
            checked(item)

    def test_fake_checked_actor_guest(self):
        self.invalid(lambda x: x["canonical_checked_ir_to_graalvm"].update(guest_executed=False))

    def test_wrong_original_compiler_blob_count(self):
        self.invalid(lambda x: x["canonical_checked_ir_to_graalvm"].update(original_source_git_blobs_verified=0))

    def test_forged_canonical_ownership_tests(self):
        self.invalid(lambda x: x["canonical_checked_ir_to_graalvm"].update(negative_source_admission_tests=0))

    def test_wrong_llvm_run_url(self):
        self.invalid(lambda x: x["canonical_checked_ir_to_graalvm"].update(
            run_url=x["graalvm_async_worker_host"]["run_url"]))

    def test_wrong_java_compiler_git_blob(self):
        self.invalid(lambda x: x["canonical_checked_ir_to_graalvm"].update(
            java_codegen_git_blob="missing"))

    def test_wrong_native_result(self):
        self.invalid(lambda x: x["canonical_checked_ir_to_graalvm"].update(native_return=44))

    def test_wrong_actor_digest(self):
        self.invalid(lambda x: x["canonical_checked_ir_to_graalvm"].update(actor_state_digest=0))

    def test_fake_native_worker_progress(self):
        self.invalid(lambda x: x["graalvm_async_worker_host"].update(concurrent_accepted_messages=0))

    def test_fake_worker_thread_concurrency(self):
        self.invalid(lambda x: x["graalvm_async_worker_host"].update(
            independent_worker_threads_observed=False))

    def test_supervisor_notice_missing(self):
        self.invalid(lambda x: x["graalvm_async_worker_host"].update(supervisor_control_notices=0))

    def test_unaccounted_abandoned_mail(self):
        self.invalid(lambda x: x["graalvm_async_worker_host"].update(abandoned_queued_messages_accounted=0))

    def test_claim_zero_allocations(self):
        self.invalid(lambda x: x["graalvm_async_worker_host"].update(managed_heap_delta_bytes=0))

    def test_claim_heap_bound_passed(self):
        self.invalid(lambda x: x["graalvm_async_worker_host"].update(managed_heap_budget="PASS"))

    def test_relax_heap_budget(self):
        self.invalid(lambda x: x["graalvm_async_worker_host"].update(
            managed_heap_growth_budget_bytes=32*1024*1024))

    def test_unearned_full_compiler_ownership(self):
        self.invalid(lambda x: x["unverified_release_gates"].update(full_canonical_hir_mir="PASS"))

    def test_unearned_async_compiled_guest(self):
        self.invalid(lambda x: x["unverified_release_gates"].update(
            compiled_atto_async_actor_scheduling="PASS"))

    def test_unearned_hostile_tenant_security(self):
        self.invalid(lambda x: x["unverified_release_gates"].update(
            production_hostile_tenant_sandbox="PASS"))

    def test_unearned_zero_gc_sustainability(self):
        self.invalid(lambda x: x["unverified_release_gates"].update(
            graalvm_sustainable_managed_heap_under_epsilon="PASS"))

    def test_unearned_wasm_actor_abi(self):
        self.invalid(lambda x: x["unverified_release_gates"].update(wasm_actor_abi="PASS"))

if __name__ == "__main__":
    unittest.main()
