// Bounded Copy-scalar model: no source compiler is invoked.
export function runModel(){
  const eq=(a,b)=>JSON.stringify(a)===JSON.stringify(b);
  const check=(p,m)=>{if(!p)throw Error(m)};
  const scalar=k=>({kind:"scalar",type:k});
  const int=scalar("int"),bool=scalar("bool");
  const tuple=(...items)=>({kind:"tuple",items});
  const row=(kind,fields)=>({kind,fields:fields.map(([name,type,visible=true])=>({name,id:`decl:${kind}:${name}`,type,visible}))});
  const base=[int,bool];
  const level1=[...base,tuple(),...base.map(a=>tuple(a)),...base.flatMap(a=>base.map(b=>tuple(a,b))),
    ...base.flatMap(a=>["record","struct","class"].map(k=>row(k,[["x",a]]))),
    ...base.flatMap(a=>base.flatMap(b=>["record","struct","class"].flatMap(k=>[row(k,[["x",a],["y",b]]),row(k,[["x",a],["y",b,false]])])))];
  // Complete depth-one domain; depth two covers each depth-one shape alone,
  // and with one scalar sibling in either order, in tuples and mixed rows.
  const domain=[...level1,...level1.filter(t=>t.kind!=="scalar").flatMap(t=>[
    tuple(t),tuple(t,int),tuple(bool,t),row("record",[["x",t],["y",int]]),
    row("struct",[["x",int],["y",t]]),row("class",[["x",t],["y",bool,false]])])];
  const shapes=[...new Map(domain.map(t=>[JSON.stringify(t),t])).values()];
  function product(lists){return lists.reduce((acc,items)=>acc.flatMap(prefix=>items.map(x=>[...prefix,x])),[[]])}
  function values(t){
    if(t.kind==="scalar")return t.type==="int"?[-1,7]:[false,true];
    if(t.kind==="tuple")return product(t.items.map(values)).map(items=>({kind:"tuple",items}));
    return product(t.fields.map(f=>values(f.type))).map(items=>({kind:t.kind,fields:Object.fromEntries(t.fields.map((f,i)=>[f.id,items[i]]))}));
  }
  // Names generated by tree location, not by selected field order.
  function patterns(t,prefix="r"){
    if(t.kind==="scalar")return [
      {kind:"bind",name:prefix,mode:"val",type:t.type},
      {kind:"bind",name:prefix,mode:"let"},
      {kind:"discard"}];
    if(t.kind==="tuple")return product(t.items.map((x,i)=>patterns(x,prefix+"_"+i))).map(items=>({kind:"tuple",items}));
    const fs=t.fields.filter(f=>f.visible), orders=fs.length===2?[[fs[0]],[fs[1]],fs,[fs[1],fs[0]]]:fs.map(f=>[f]);
    return orders.flatMap(order=>product(order.map(f=>patterns(f.type,prefix+"_"+f.name))).map(ps=>({kind:"fields",items:order.map((f,i)=>({name:f.name,pattern:ps[i]}))})));
  }
  // Reference semantics recursively visits source pattern + shape + value.
  // It does not call the planner or path interpreter.
  function reference(roots,ps,vs){
    if(roots.length!==ps.length||ps.length!==vs.length)throw Error("root arity");
    const names=new Set(),out=[];
    function visit(t,p,v){
      if(p.kind==="bind"||p.kind==="discard"){
        if(t.kind!=="scalar"||(p.type&&p.type!==t.type))throw Error("scalar type");
        if(p.kind==="bind"){
          if(names.has(p.name)||["self","arguments"].includes(p.name)||!["val","let"].includes(p.mode))throw Error("binder");
          names.add(p.name);out.push([p.name,p.mode,v]);
        }
        return;
      }
      if(p.kind==="tuple"){
        if(t.kind!=="tuple"||p.items.length!==t.items.length)throw Error("tuple arity");
        for(let i=0;i<p.items.length;i++)visit(t.items[i],p.items[i],v.items[i]);
        return;
      }
      if(p.kind!=="fields"||!["record","struct","class"].includes(t.kind)||!p.items.length)throw Error("field shape");
      const seen=new Set();
      for(const item of p.items){
        const f=t.fields.find(f=>f.name===item.name);
        if(!f||!f.visible||seen.has(item.name))throw Error("selector");
        seen.add(item.name);visit(f.type,item.pattern,v.fields[f.id]);
      }
    }
    for(let i=0;i<roots.length;i++)visit(roots[i],ps[i],vs[i]);
    return out;
  }
  // Separate implementation: resolve paths first, then interpret an immutable
  // projection list. Never call the reference evaluator.
  function plan(roots,ps){
    if(roots.length!==ps.length)throw Error("root arity");
    const instructions=[],names=new Set();
    const work=ps.map((p,i)=>({p,t:roots[i],root:i,path:[]})).reverse();
    while(work.length){
      const {p,t,root,path}=work.pop();
      switch(p.kind){
        case "bind":case "discard":
          if(t.kind!=="scalar"||("type" in p&&p.type!==t.type))throw Error("leaf type");
          if(p.kind==="bind"){
            if(!["val","let"].includes(p.mode)||names.has(p.name)||p.name==="self"||p.name==="arguments")throw Error("binder");
            names.add(p.name);
          }
          instructions.push({root,path,type:t.type,kind:p.kind,name:p.name,mode:p.mode});
          break;
        case "tuple":
          if(t.kind!=="tuple"||t.items.length!==p.items.length)throw Error("tuple arity");
          for(let i=p.items.length-1;i>=0;i--)work.push({p:p.items[i],t:t.items[i],root,path:[...path,{index:i}]});
          break;
        case "fields":{
          if(!["record","struct","class"].includes(t.kind)||p.items.length===0)throw Error("field shape");
          const byName=new Map(t.fields.filter(f=>f.visible).map(f=>[f.name,f]));
          const seen=new Set();
          for(let i=p.items.length-1;i>=0;i--){
            const item=p.items[i],field=byName.get(item.name);
            if(!field||seen.has(field.id))throw Error("selector");
            seen.add(field.id);work.push({p:item.pattern,t:field.type,root,path:[...path,{field:field.id}]});
          }
          break;
        }
        default:throw Error("unknown pattern");
      }
    }
    return {arity:roots.length,instructions};
  }
  function execute(ir,roots){
    check(ir.arity===roots.length,"ABI arity");
    const out=[];
    for(const i of ir.instructions){
      let v=roots[i.root];
      for(const s of i.path)v="index" in s?v.items[s.index]:v.fields[s.field];
      check(i.type==="int"?Number.isInteger(v):typeof v==="boolean","runtime scalar type");
      if(i.kind==="bind")out.push([i.name,i.mode,v]);
    }
    return out;
  }
  let comparisons=0, plans=0, invalid=0, roots=0, rebinds=0;
  function compare(types,ps,vs,ir){
    const before=JSON.stringify(vs);
    const expected=reference(types,ps,vs),actual=execute(ir,vs);
    check(eq(expected,actual),"reference refinement mismatch");
    check(JSON.stringify(vs)===before,"root changed");
    // Local scalar rebinding cannot mutate any root.
    for(const slot of actual)if(slot[1]==="let"){slot[2]=typeof slot[2]==="boolean"?!slot[2]:slot[2]+1;rebinds++;}
    check(JSON.stringify(vs)===before,"local rebind modified root");
    comparisons++;
  }
  for(const t of shapes){
    for(const p of patterns(t)){
      const ir=plan([t],[p]);check(ir.arity===1,"flattened root arity");plans++;
      for(const v of values(t))compare([t],[p],[v],ir);
    }
  }
  // Two roots: all depth-one root shape pairs; representative first/last
  // legal patterns and values. Distinct namespaces are required across slots.
  for(const a of level1)for(const b of level1){
    const pa=patterns(a,"a"),pb=patterns(b,"b");
    for(const x of [pa[0],pa.at(-1)])for(const y of [pb[0],pb.at(-1)]){
      const ir=plan([a,b],[x,y]);check(ir.arity===2,"root arity");roots++;
      for(const v of [values(a)[0],values(a).at(-1)])for(const w of [values(b)[0],values(b).at(-1)])compare([a,b],[x,y],[v,w],ir);
    }
  }
  const bind=(name="a",type)=>({kind:"bind",name,mode:"val",...(type?{type}:{})});
  const discard={kind:"discard"},pair=tuple(int,int),record=row("record",[["x",int],["y",int,false]]);
  const field=(name,p=bind())=>({name,pattern:p});
  const tp=(...items)=>({kind:"tuple",items}),fp=(...items)=>({kind:"fields",items});
  const rejected=[
    [[pair],[tp(bind())]],[[pair],[tp(bind(),bind("b"),discard)]],[[int],[tp(bind())]],
    [[tuple()],[tp(bind())]],[[pair],[tp()]],[[record],[fp(field("missing"))]],
    [[record],[fp(field("y"))]],[[record],[fp(field("x"),field("x",bind("b")))]],
    [[record],[fp()]],[[pair],[tp(bind("a"),bind("a"))]],[[pair],[tp(bind("self"),discard)]],
    [[pair],[tp(bind("a","bool"),discard)]],[[pair],[bind()]],[[int,int],[bind("a"),bind("a")]],
    [[int],[bind(),bind("b")]],[[int],[{kind:"bind",name:"a",mode:"const"}]],
    [[int],[fp(field("x"))]],[[record],[tp(bind(),discard)]]
  ];
  for(const [ts,ps] of rejected){
    let a=false,b=false;try{reference(ts,ps,ts.map(t=>values(t)[0]))}catch{a=true}
    try{plan(ts,ps)}catch{b=true}check(a&&b,"invalid pattern admitted");invalid++;
  }
  // Argument effects are external to projections. Model a failing argument
  // at every possible slot, and compare left-to-right single evaluation.
  function argumentRun(thunks,ir){
    const trace=[],vs=[];
    for(let i=0;i<thunks.length;i++){
      trace.push(i);if(thunks[i].fail)return {trace,fault:i};
      vs.push(thunks[i].value);
    }
    return {trace,bindings:execute(ir,vs)};
  }
  let effectChecks=0;
  for(let n=0;n<=4;n++){
    const ts=Array(n).fill(int),ps=ts.map((_,i)=>bind("p"+i)),ir=plan(ts,ps);
    for(let fault=-1;fault<n;fault++){
      const thunks=ts.map((_,i)=>({fail:fault===i,value:i}));
      const got=argumentRun(thunks,ir),expectedTrace=Array.from({length:fault<0?n:fault+1},(_,i)=>i);
      check(eq(got.trace,expectedTrace),"argument evaluation order");
      if(fault>=0)check(got.fault===fault&&!Object.hasOwn(got,"bindings"),"fault did not stop");
      else check(eq(got.bindings,reference(ts,ps,thunks.map(t=>t.value))),"successful call mismatch");
      effectChecks++;
    }
  }
  // Mutation witnesses: a model checker that accepts known wrong lowerings
  // is inadequate. Each intentionally wrong plan must fail observably.
  const ts=[pair],ps=[tp(bind("a"),bind("b"))],vs=[{kind:"tuple",items:[-1,7]}],ir=plan(ts,ps);
  const expected=reference(ts,ps,vs),mutants=[
    ["flattened ABI",{...ir,arity:2}],
    ["reversed projections",{...ir,instructions:[...ir.instructions].reverse()}],
    ["duplicate projection",{...ir,instructions:[ir.instructions[0],ir.instructions[0]]}],
    ["wrong tuple index",{...ir,instructions:[{...ir.instructions[0],path:[{index:1}]},ir.instructions[1]]}],
    ["lost binding",{...ir,instructions:ir.instructions.slice(0,1)}],
    ["wrong binding mode",{...ir,instructions:[{...ir.instructions[0],mode:"let"},ir.instructions[1]]}]
  ];
  for(const [name,broken] of mutants){
    let detected=false;try{detected=!eq(execute(broken,vs),expected)}catch{detected=true}
    check(detected,"undetected mutant "+name);
  }
  return {status:"MODEL_ONLY",shapeCount:shapes.length,depthOneShapes:level1.length,typedPlans:plans,twoRootPlans:roots,comparisons,localRebindings:rebinds,invalidPatterns:invalid,effectChecks,mutantsDetected:mutants.map(x=>x[0]),compilerExecuted:false,nonCopyOwnershipProven:false};
}

console.log(JSON.stringify(runModel(), null, 2));
